#!/usr/bin/env bash
#
# StxSaryus's Arch Hyprland Dotfiles — Fully Automatic Installer
#
# Usage:
#   ./install.sh              # Auto install (recommended defaults, one confirm)
#   ./install.sh --auto       # Same, no confirm (CI / reinstall)
#   ./install.sh --interactive  # Choose apps / shortcuts
#   ./install.sh --configs    # Link configs only
#   ./install.sh --help
#
# Official references shown during install:
#   https://archlinux.org/news/nvidia-590-driver-drops-pascal-support-main-packages-switch-to-open-kernel-modules/
#   https://wiki.hypr.land/Configuring/
#   https://wiki.archlinux.org/title/NVIDIA
#
set -euo pipefail


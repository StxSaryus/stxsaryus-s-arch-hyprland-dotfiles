install_aur_packages() {
    section "AUR packages (yay)"
    ensure_yay
    local aur=(oh-my-zsh-git zsh-theme-powerlevel10k-git)
    [[ "$OPT_WAYPAPER" -eq 1 ]] && aur+=(waypaper-git)

    # One AUR package failing to build must not take the whole install with
    # it — the configs still need to be linked. Report and carry on.
    local pkg failed=()
    for pkg in "${aur[@]}"; do
        yay -S --needed --noconfirm "$pkg" || failed+=("$pkg")
    done
    if (( ${#failed[@]} )); then
        warn "AUR packages that did not install: ${failed[*]}"
        warn "Install them later with: yay -S ${failed[*]}"
    else
        success "AUR packages installed"
    fi
}

setup_nvidia() {
    [[ "$OPT_NVIDIA" -eq 1 ]] || return 0
    [[ "$NVIDIA_DRIVER" == "none" ]] && return 0

    section "NVIDIA driver"
    need_sudo

    sudo install -Dm644 "$REPO/nvidia/modprobe-nvidia.conf" /etc/modprobe.d/nvidia.conf
    sudo install -Dm644 "$REPO/nvidia/blacklist-nouveau.conf" /etc/modprobe.d/blacklist-nouveau.conf
    sudo install -Dm644 "$REPO/nvidia/modules-load-nvidia.conf" /etc/modules-load.d/nvidia.conf
    success "modprobe / modules-load / nouveau blacklist installed"

    if [[ -f /etc/default/grub ]] && ! grep -q 'nvidia_drm.modeset=1' /etc/default/grub; then
        info "GRUB: adding nvidia_drm.modeset=1 (Arch Wiki NVIDIA / Hyprland)"
        sudo sed -i 's/^GRUB_CMDLINE_LINUX_DEFAULT="\(.*\)"/GRUB_CMDLINE_LINUX_DEFAULT="\1 nvidia_drm.modeset=1"/' /etc/default/grub
        sudo grub-mkconfig -o /boot/grub/grub.cfg
        success "GRUB updated"
    fi

    if [[ "$NVIDIA_DRIVER" == "580xx" ]]; then
        info "Removing nvidia-open / conflicting nvidia-utils 590+ ..."
        sudo pacman -Rns --noconfirm nvidia-open nvidia-open-dkms nvidia-open-lts 2>/dev/null || true
        if pacman -Q nvidia-utils &>/dev/null && ! pacman -Q nvidia-580xx-utils &>/dev/null; then
            sudo pacman -Rdd --noconfirm nvidia-utils 2>/dev/null || true
        fi
        ensure_yay
        info "Installing nvidia-580xx-dkms + nvidia-580xx-utils (may take several minutes)..."
        yay -S --needed --noconfirm nvidia-580xx-dkms nvidia-580xx-utils

        info "DKMS: building module for kernel $(uname -r)..."
        # AUR package often leaves status "added" only — force install for current kernel
        if command -v dkms >/dev/null; then
            local ver=""
            ver="$(dkms status 2>/dev/null | awk -F'[/,: ]+' '/^nvidia\//{print $2; exit}')"
            if [[ -n "$ver" ]]; then
                sudo dkms install "nvidia/${ver}" -k "$(uname -r)" 2>/dev/null \
                    || sudo dkms autoinstall \
                    || warn "DKMS install had issues — reboot may still work"
            else
                sudo dkms autoinstall || true
            fi
            dkms status 2>/dev/null || true
        fi
    else
        info "Installing nvidia-open + nvidia-utils from official repos..."
        sudo pacman -S --needed --noconfirm nvidia-open nvidia-utils
    fi

    sudo modprobe nvidia 2>/dev/null || true
    sudo modprobe nvidia_uvm 2>/dev/null || true
    sudo modprobe nvidia_modeset 2>/dev/null || true
    sudo modprobe nvidia_drm 2>/dev/null || true

    if nvidia-smi &>/dev/null; then
        success "nvidia-smi: $(nvidia-smi --query-gpu=name,driver_version --format=csv,noheader)"
    else
        warn "nvidia-smi not ready — reboot required after DKMS (expected on first install)"
    fi
}

backup_and_link() {
    local src="$1" dest="$2"
    mkdir -p "$(dirname "$dest")"
    if [[ -e "$dest" && ! -L "$dest" ]]; then
        mv "$dest" "${dest}.bak.$(date +%s)"
        warn "Backed up: $dest"
    fi
    ln -sf "$src" "$dest"
}

# For files the applications write back into (wallpaper state, waypaper's own
# settings). Symlinking those would have them edit the git checkout.
copy_if_missing() {
    local src="$1" dest="$2"
    mkdir -p "$(dirname "$dest")"
    [[ -L "$dest" ]] && rm -f "$dest"
    [[ -e "$dest" ]] && return 0
    cp "$src" "$dest"
}

# Leftovers from older versions of this repo
clean_stale_links() {
    local stale=(
        "$HOME/.config/hypr/brightness-osd.sh"
        "$HOME/.config/waybar/gpu_stats.sh"
    )
    local f
    for f in "${stale[@]}"; do
        [[ -L "$f" ]] && rm -f "$f" && info "Removed stale link: ${f/#$HOME/\~}"
    done

    # waypaper/config.ini is never overwritten, so a copy made by an earlier
    # version still carries "stylesheet = ~/...". Waypaper is the one path
    # option it does not expand ~ for, and it drops the theme without a word.
    local wp="$HOME/.config/waypaper/config.ini"
    if [[ -f "$wp" && ! -L "$wp" ]] && grep -q '^stylesheet[[:space:]]*=[[:space:]]*~' "$wp"; then
        sed -i '/^stylesheet[[:space:]]*=[[:space:]]*~/d;/^keybindings[[:space:]]*=[[:space:]]*~/d' "$wp"
        info "Removed the unexpandable stylesheet path from waypaper/config.ini"
    fi
    return 0
}

copy_and_patch_hypr() {
    mkdir -p "$(dirname "$HYPR_CONF")"
    if [[ -e "$HYPR_CONF" && ! -L "$HYPR_CONF" ]]; then
        mv "$HYPR_CONF" "${HYPR_CONF}.bak.$(date +%s)"
        warn "Backed up: $HYPR_CONF"
    fi
    cp "$REPO/config/hypr/hyprland.conf" "$HYPR_CONF"
}

# hyprland.conf declares $terminal / $browser / ... once at the top and every
# bind refers to those, so a choice is a single line rewrite.
set_hypr_var() {
    local name="$1" value="$2"
    value="${value//\\/\\\\}"
    value="${value//&/\\&}"
    value="${value//|/\\|}"
    sed -i "s|^[\$]${name} = .*|\$${name} = ${value}|" "$HYPR_CONF"
}

set_hypr_key() {
    local default_key="$1" new_key="$2" var="$3"
    [[ "$default_key" == "$new_key" ]] && return 0
    sed -i "s|^bind = [\$]mainMod, ${default_key}, exec, [\$]${var}\$|bind = \$mainMod, ${new_key}, exec, \$${var}|" "$HYPR_CONF"
}

patch_hyprland_conf() {
    set_hypr_var terminal "$TERMINAL_CMD"
    set_hypr_var browser "$BROWSER_CMD"
    set_hypr_var fileManager "$FILE_MANAGER_CMD"
    set_hypr_var launcher "$LAUNCHER_CMD"

    set_hypr_key T "$KEY_TERMINAL" terminal
    set_hypr_key B "$KEY_BROWSER" browser
    set_hypr_key E "$KEY_FILE_MANAGER" fileManager
    set_hypr_key SPACE "$KEY_LAUNCHER" launcher
    set_hypr_key L "$KEY_LOCK" lockCmd
}

link_configs() {
    section "Linking configs"
    clean_stale_links

    if [[ -f "$HYPR_DEST/hyprland.lua" ]]; then
        mv "$HYPR_DEST/hyprland.lua" "$HYPR_DEST/hyprland.lua.bak.$(date +%s)"
        warn "Moved hyprland.lua aside (Hyprland 0.55+ prefers .lua over .conf)"
    fi

    local f

    # The palette every other config reads
    for f in palette.conf build-theme.sh colors.css colors.rasi colors-kitty.conf colors-hypr.conf; do
        backup_and_link "$REPO/config/theme/$f" "$HOME/.config/theme/$f"
    done

    for f in waybar-autohide.sh osd.sh wallpaper-sync.sh apply-dark-theme.sh hyprlock.conf hypridle.conf; do
        backup_and_link "$REPO/config/hypr/$f" "$HOME/.config/hypr/$f"
    done
    copy_if_missing "$REPO/config/hypr/hyprpaper.conf" "$HOME/.config/hypr/hyprpaper.conf"

    mkdir -p "$HOME/.config/gtk-3.0" "$HOME/.config/gtk-4.0"
    for f in settings.ini gtk.css; do
        backup_and_link "$REPO/config/gtk-3.0/$f" "$HOME/.config/gtk-3.0/$f"
        backup_and_link "$REPO/config/gtk-4.0/$f" "$HOME/.config/gtk-4.0/$f"
    done
    backup_and_link "$REPO/config/gtk-2.0/.gtkrc-2.0" "$HOME/.gtkrc-2.0"

    mkdir -p "$HOME/.config/waybar/scripts"
    for f in config.jsonc style.css sys_stats.sh; do
        backup_and_link "$REPO/config/waybar/$f" "$HOME/.config/waybar/$f"
    done
    for f in lock-icon.sh lock-toggle.sh; do
        backup_and_link "$REPO/config/waybar/scripts/$f" "$HOME/.config/waybar/scripts/$f"
    done

    backup_and_link "$REPO/config/rofi/config.rasi" "$HOME/.config/rofi/config.rasi"
    backup_and_link "$REPO/config/kitty/kitty.conf" "$HOME/.config/kitty/kitty.conf"

    for f in config.json style.css; do
        backup_and_link "$REPO/config/swaync/$f" "$HOME/.config/swaync/$f"
    done
    for f in bar.json style.css; do
        backup_and_link "$REPO/config/nwg-bar/$f" "$HOME/.config/nwg-bar/$f"
    done

    backup_and_link "$REPO/config/waypaper/style.css" "$HOME/.config/waypaper/style.css"
    copy_if_missing "$REPO/config/waypaper/config.ini" "$HOME/.config/waypaper/config.ini"

    mkdir -p "$HOME/.local/share/bin"
    for f in launcher-toggle.sh waypaper-toggle.sh session-menu.sh systemupdate.sh; do
        backup_and_link "$REPO/config/local-bin/$f" "$HOME/.local/share/bin/$f"
    done

    backup_and_link "$REPO/zsh/.zshrc" "$HOME/.zshrc"
    backup_and_link "$REPO/bash/.bashrc" "$HOME/.bashrc"

    copy_and_patch_hypr
    patch_hyprland_conf
    success "Configs linked + hyprland.conf patched"
}

set_permissions() {
    chmod +x \
        "$HOME/.config/hypr/"*.sh \
        "$HOME/.config/theme/build-theme.sh" \
        "$HOME/.config/waybar/"*.sh \
        "$HOME/.config/waybar/scripts/"*.sh \
        "$HOME/.local/share/bin/"*.sh \
        "$REPO/nvidia/setup-nvidia.sh" 2>/dev/null || true
    echo "1" > "$HOME/.config/waybar/.pinned"
    # Apply dark theme immediately when gsettings is available
    if [[ -x "$HOME/.config/hypr/apply-dark-theme.sh" ]]; then
        bash "$HOME/.config/hypr/apply-dark-theme.sh" 2>/dev/null || true
    fi
}

setup_default_wallpaper() {
    local wp_dir="$HOME/Wallpapers"
    local wp_file="$wp_dir/default.png"
    mkdir -p "$wp_dir"
    if [[ ! -f "$wp_file" && -f /usr/share/hypr/wall0.png ]]; then
        cp /usr/share/hypr/wall0.png "$wp_file"
        success "Default wallpaper → $wp_file"
    fi
    if [[ -f "$wp_file" ]]; then
        # Resolved path (hyprpaper does not expand ~ reliably)
        cat > "$HOME/.config/hypr/hyprpaper.conf" <<EOF
preload = ${wp_file}
wallpaper = ,contain:${wp_file}
splash = false
EOF
    fi
}


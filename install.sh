parse_args() {
    case "${1:-}" in
        "") MODE="auto" ;;
        --auto) MODE="auto"; SKIP_CONFIRM=1 ;;
        --interactive) MODE="interactive" ;;
        --configs) MODE="configs" ;;
        --packages) MODE="packages" ;;
        -h|--help) usage; exit 0 ;;
        *) error "Unknown option: $1 (try --help)" ;;
    esac
}

need_sudo() {
    if ! sudo -n true 2>/dev/null; then
        info "sudo password required..."
        sudo -v || error "sudo failed"
    fi
    if [[ -z "$SUDO_KEEPALIVE_PID" ]]; then
        ( while true; do sudo -n true; sleep 50; kill -0 "$$" || exit; done ) 2>/dev/null &
        SUDO_KEEPALIVE_PID=$!
        trap 'kill "$SUDO_KEEPALIVE_PID" 2>/dev/null || true' EXIT
    fi
}

detect_gpu() {
    local gpu_line
    gpu_line="$(lspci -nn 2>/dev/null | grep -iE 'VGA|3D|Display' | grep -i nvidia | head -1 || true)"
    local pci_id=""
    if [[ -n "$gpu_line" ]]; then
        pci_id="$(echo "$gpu_line" | grep -oE '10de:[0-9a-fA-F]+' | cut -d: -f2 | head -1 || true)"
    fi

    NVIDIA_DRIVER="none"
    if [[ -z "$gpu_line" ]]; then
        OPT_NVIDIA=0
        info "No NVIDIA GPU detected — skipping NVIDIA driver"
        return
    fi

    info "NVIDIA GPU: $gpu_line"
    # Pascal = 1bxx/1cxx, Maxwell = 13xx/14xx, Kepler and older = lower
    case "${pci_id,,}" in
        1c*|1b*|1d80|1d81|1d82|14*|13*|12*|11*|0f*|0e*|0c*|0a*|019*)
            NVIDIA_DRIVER="580xx"
            warn "Pascal/older → AUR nvidia-580xx-dkms (Arch News: NVIDIA 590 dropped Pascal)"
            ;;
        *)
            if journalctl -b -k --no-pager 2>/dev/null | grep -q "not supported by open"; then
                NVIDIA_DRIVER="580xx"
                warn "Open module rejected GPU (no GSP) → forcing nvidia-580xx-dkms"
            else
                NVIDIA_DRIVER="open"
                info "Assuming Turing+ → repo nvidia-open"
            fi
            ;;
    esac
}

ensure_yay() {
    export PATH="$HOME/.local/bin:/usr/local/bin:$PATH"
    if command -v yay >/dev/null 2>&1; then
        success "yay: $(command -v yay)"
        return
    fi
    section "Installing yay (AUR helper)"
    need_sudo
    sudo pacman -S --needed --noconfirm base-devel git
    local tmp
    tmp="$(mktemp -d)"
    git clone --depth 1 https://aur.archlinux.org/yay-bin.git "$tmp/yay-bin"
    ( cd "$tmp/yay-bin" && makepkg -si --noconfirm )
    rm -rf "$tmp"
    hash -r
    command -v yay >/dev/null || error "yay install failed"
    success "yay installed"
}


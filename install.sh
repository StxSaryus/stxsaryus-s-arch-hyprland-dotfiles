        firefox) pkgs+=(firefox) ;;
        chromium) pkgs+=(chromium) ;;
        brave-browser) pkgs+=(brave-browser) ;;
        librewolf) pkgs+=(librewolf) ;;
        *) pkgs+=(firefox) ;;
    esac
    case "$FILE_MANAGER_CMD" in
        thunar) pkgs+=(thunar) ;;
